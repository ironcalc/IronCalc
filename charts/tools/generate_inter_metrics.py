#!/usr/bin/env python3
"""Dumps the advance widths of Inter as a Rust table.

Usage (needs `fonttools` and `brotli`):

    python3 charts/tools/generate_inter_metrics.py > charts/src/text/inter_v13.rs

The widths are read from the font files the webapp ships, so the layout
measures text with the same font the browser draws it with. Run it again when
those files change.
"""

from fontTools.ttLib import TTFont

FONTS = [
    ("REGULAR", "webapp/IronCalc/fonts/inter-v13-latin-regular.woff2"),
    ("SEMIBOLD", "webapp/IronCalc/fonts/inter-v13-latin-600.woff2"),
]
# ASCII and Latin-1: the ranges the table covers, see `advance` in metrics.rs
RANGES = [(0x20, 0x7F), (0xA0, 0x100)]


def main():
    print("//! Advance widths of Inter v13, in font units, generated by")
    print("//! `charts/tools/generate_inter_metrics.py`. Do not edit by hand.")
    print()
    first = True
    for name, path in FONTS:
        font = TTFont(path)
        cmap = font.getBestCmap()
        hmtx = font["hmtx"]
        if first:
            head, hhea = font["head"], font["hhea"]
            print(f"pub const UNITS_PER_EM: f64 = {head.unitsPerEm}.0;")
            print(f"pub const ASCENDER: f64 = {hhea.ascent}.0;")
            print(f"pub const DESCENDER: f64 = {hhea.descent}.0;")
            print(f"pub const AVERAGE_ADVANCE: f64 = {font['OS/2'].xAvgCharWidth}.0;")
            first = False
        widths = []
        for start, end in RANGES:
            for code_point in range(start, end):
                widths.append(hmtx[cmap[code_point]][0])
        print()
        print(f"/// U+0020..U+007E followed by U+00A0..U+00FF.")
        print(f"pub const {name}: [u16; {len(widths)}] = [")
        for i in range(0, len(widths), 12):
            print("    " + ", ".join(str(w) for w in widths[i : i + 12]) + ",")
        print("];")


if __name__ == "__main__":
    main()
