use std::fs;
use std::path::PathBuf;

use ironcalc::import::load_from_xlsx;
use ironcalc_base::types::{
    Alignment, Border, BorderItem, BorderStyle, Color, Fill, Font, HorizontalAlignment, MergedCell,
    Style, VerticalAlignment,
};
use ironcalc_base::Model;
use ironcalc_pdf::{
    export_to_pdf_file, BookmarkPolicy, ExportScope, HeaderFooterField, HeaderFooterLayout,
    Margins, PaperSize, PdfExportOptions,
};

fn manifest_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn xlsx_path(relative: &str) -> PathBuf {
    manifest_dir().join("../xlsx").join(relative)
}

fn output_dir() -> PathBuf {
    let dir = manifest_dir().join("tests/output");
    fs::create_dir_all(&dir).expect("failed to create pdf/tests/output directory");
    dir
}

#[test]
fn test_generate_invoice_pdf() {
    let input = xlsx_path("tests/templates/invoice.xlsx");
    assert!(input.exists(), "input file {:?} must exist", input);

    let model = load_from_xlsx(input.to_str().unwrap(), "en", "UTC", "en")
        .expect("failed to load invoice.xlsx");

    let out_file = output_dir().join("invoice.pdf");
    let options = PdfExportOptions::default()
        .with_paper_size(PaperSize::A4)
        .portrait()
        .with_margins(Margins::normal())
        .with_scope(ExportScope::ActiveSheet)
        .fit_to_page()
        .with_centering(true, false)
        .with_gridlines(false)
        .with_headings(false)
        .with_header_footer(
            HeaderFooterLayout {
                left: HeaderFooterField::Text("INVOICE REPORT".to_string()),
                center: HeaderFooterField::Empty,
                right: HeaderFooterField::Date,
            },
            HeaderFooterLayout {
                left: HeaderFooterField::Text("Generated by IronCalc".to_string()),
                center: HeaderFooterField::Empty,
                right: HeaderFooterField::PageNumberOfTotal,
            },
        )
        .with_bookmarks(BookmarkPolicy::AlwaysBySheet);

    export_to_pdf_file(&model, &options, out_file.to_str().unwrap())
        .expect("failed to export invoice.pdf");

    assert!(out_file.exists());
    let metadata = fs::metadata(&out_file).unwrap();
    assert!(metadata.len() > 1000, "invoice.pdf should not be empty");
    println!("Generated visual PDF: {:?}", out_file);
}

